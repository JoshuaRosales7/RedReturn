import { describe, expect, it } from "vitest";
import { coordinateToVector, vectorToCoordinate, DEFAULT_CONFIG, evaluateMission, evaluateSummary, flatSummary, greatCircleDistance, initialBearing, interpolateGreatCircle, normalizeLon, MARS_RADIUS_KM } from "../lib/mars";
import { buildConceptualTerrain, conceptualElevationM } from "../lib/terrain";
import { CATALOG, LAYERS, tileUrl } from "../data/catalog";
import { apiConfig, fromApiConfig } from "../lib/store";

describe("Mars geodesy", () => {
  it("returns zero for identical points", () => expect(greatCircleDistance({ lat: 0, lon: 0 }, { lat: 0, lon: 0 })).toBe(0));
  it("one degree on the equator", () => expect(greatCircleDistance({ lat: 0, lon: 0 }, { lat: 0, lon: 1 })).toBeCloseTo(MARS_RADIUS_KM * Math.PI / 180, 9));
  it("handles the antimeridian by shortest arc", () => expect(greatCircleDistance({ lat: 0, lon: 179 }, { lat: 0, lon: -179 })).toBeCloseTo(2 * MARS_RADIUS_KM * Math.PI / 180, 6));
  it("handles polar coordinates", () => expect(greatCircleDistance({ lat: 90, lon: 0 }, { lat: 90, lon: 170 })).toBeLessThan(1e-4));
  it("normalizes longitudes", () => { expect(normalizeLon(190)).toBe(-170); expect(normalizeLon(-190)).toBe(170); expect(normalizeLon(360)).toBe(0); });
  it("interpolates finite points across antimeridian and near poles", () => {
    expect(interpolateGreatCircle({ lat: 10, lon: 179 }, { lat: 12, lon: -179 }).every(p => Number.isFinite(p.lat + p.lon))).toBe(true);
    expect(interpolateGreatCircle({ lat: 89.5, lon: 0 }, { lat: 89.5, lon: 180 }).every(p => Number.isFinite(p.lat + p.lon))).toBe(true);
  });
  it("computes a cardinal initial bearing", () => expect(initialBearing({ lat: 0, lon: 0 }, { lat: 0, lon: 10 })).toBeCloseTo(90));
});

describe("Mission model (TypeScript mirror)", () => {
  const route = [{ lat: 0, lon: 0 }, { lat: 0, lon: 0.1 }];
  it("accounts for the required return", () => expect(evaluateMission(route, DEFAULT_CONFIG).distanceKm).toBeCloseTo(greatCircleDistance(route[0], route[1]) * 2));
  it("rejects impossible oxygen, water and time budgets", () => {
    expect(evaluateMission(route, { ...DEFAULT_CONFIG, oxygenKg: 0 }).constraints.oxygen).toBe(false);
    expect(evaluateMission(route, { ...DEFAULT_CONFIG, waterLiters: 0 }).constraints.water).toBe(false);
    expect(evaluateMission(route, { ...DEFAULT_CONFIG, maxHours: 0.01 }).constraints.time).toBe(false);
    expect(evaluateMission(route, { ...DEFAULT_CONFIG, maxRadiationMsv: 0.001 }).constraints.radiation).toBe(false);
  });
  it("climbing costs energy and time", () => {
    const flat = evaluateSummary(flatSummary(10), DEFAULT_CONFIG);
    const hill = evaluateSummary({ oneWayKm: 10, effectiveKm: 11, ascentOutM: 300, ascentBackM: 100, terrainEvaluated: true }, DEFAULT_CONFIG);
    expect(hill.energyUsedKwh).toBeGreaterThan(flat.energyUsedKwh);
    expect(hill.durationHours).toBeGreaterThan(flat.durationHours);
  });
});

type Golden = { mission: Record<string, { route: { one_way_km: number; effective_km: number; ascent_out_m: number; ascent_back_m: number; terrain_evaluated: boolean }; config: Record<string, number | boolean>;
  expected: Record<string, number | string | boolean> }>; geodesy: { a: [number, number]; b: [number, number]; km: number }[]; normalize_lon: [number, number][] };

describe("Frontend/backend parity (golden vectors generated by the Python engine)", async () => {
  const golden: Golden = (await import("./golden/mission_vectors.json")).default as unknown as Golden;
  for (const [name, c] of Object.entries(golden.mission)) {
    it(`mission vector: ${name}`, () => {
      const cfg = { ...DEFAULT_CONFIG, ...fromApiConfig(c.config) };
      const r = evaluateSummary({ oneWayKm: c.route.one_way_km, effectiveKm: c.route.effective_km, ascentOutM: c.route.ascent_out_m, ascentBackM: c.route.ascent_back_m, terrainEvaluated: c.route.terrain_evaluated }, cfg);
      const e = c.expected;
      expect(r.distanceKm).toBeCloseTo(e.distance_km as number, 9);
      expect(r.durationHours).toBeCloseTo(e.duration_hours as number, 9);
      expect(r.oxygenUsedKg).toBeCloseTo(e.oxygen_used_kg as number, 9);
      expect(r.energyUsedKwh).toBeCloseTo(e.energy_used_kwh as number, 9);
      expect(r.waterUsedLiters).toBeCloseTo(e.water_used_liters as number, 9);
      expect(r.radiationMsv).toBeCloseTo(e.radiation_msv as number, 9);
      expect(r.energyRemaining).toBeCloseTo(e.energy_remaining_kwh as number, 9);
      expect(r.limitingFactor).toBe(e.limiting_factor);
      expect(r.feasible).toBe(e.feasible_within_model);
    });
  }
  it("geodesy vectors", () => { for (const g of golden.geodesy) expect(greatCircleDistance({ lat: g.a[0], lon: g.a[1] }, { lat: g.b[0], lon: g.b[1] })).toBeCloseTo(g.km, 8); });
  it("longitude normalisation vectors", () => { for (const [raw, want] of golden.normalize_lon) expect(normalizeLon(raw)).toBeCloseTo(want, 9); });
  it("config mapping round-trips", () => expect(fromApiConfig(apiConfig(DEFAULT_CONFIG) as Record<string, number | boolean>)).toEqual(DEFAULT_CONFIG));
});

describe("Conceptual terrain (educational mode only)", () => {
  const route = [{ lat: 18.38, lon: 77.58 }, { lat: 18.65, lon: 78.15 }];
  it("is deterministic", () => { expect(buildConceptualTerrain(route, 41).profile).toEqual(buildConceptualTerrain(route, 41).profile); expect(conceptualElevationM(1.2, -.4, 12345)).toBe(conceptualElevationM(1.2, -.4, 12345)); });
  it("produces finite metrics", () => expect(buildConceptualTerrain(route).profile.every(p => Number.isFinite(p.elevationM + p.slopeDeg + p.roughness))).toBe(true));
});

describe("Catalog", () => {
  it("has valid bounded coordinates", () => { expect(CATALOG.length).toBeGreaterThanOrEqual(15); for (const c of CATALOG) { expect(Math.abs(c.lat)).toBeLessThanOrEqual(90); expect(Math.abs(c.lon)).toBeLessThanOrEqual(180); expect(c.name.length).toBeGreaterThan(0); } });
  it("builds layer tile urls for both level-0 columns", () => { for (const l of LAYERS) { expect(tileUrl(l.id, 0)).toMatch(/\/0\/0\/0\.(jpg|png)$/); expect(tileUrl(l.id, 1)).toMatch(/\/0\/0\/1\.(jpg|png)$/); } });
});

describe("Globe picking", () => {
  it.each([[18.38, 77.58], [-5.4, 137.8], [0, -120], [60, 10], [-85, 179.5], [0, 0]])("round-trips %s, %s through the globe projection", (lat, lon) => {
    const [x, y, z] = coordinateToVector({ lat, lon }, 2.0);
    const p = vectorToCoordinate(x, y, z);
    expect(p.lat).toBeCloseTo(lat, 9);
    expect(((p.lon - lon + 540) % 360) - 180).toBeCloseTo(0, 9);
  });
});
